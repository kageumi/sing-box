#!/bin/bash

# sing-box installation script

# Global variables
BASE_DIR="/root/sing-box"
INSTALL_DIR="${BASE_DIR}/bin"
CONFIG_DIR="${BASE_DIR}/config"
SERVICE_FILE="/etc/systemd/system/sing-box.service"
CONFIG_FILE="${CONFIG_DIR}/config.json"
DOMAIN="gateway.icloud.com"
PORT=443
UUID=""
PRIVATE_KEY=""
PUBLIC_KEY=""
SHORT_ID=""
TEMP_DIR=""
UNINSTALL=false

# Colors
GREEN="\033[1;32m"
RED="\033[1;31m"
BLUE="\033[1;34m"
YELLOW="\033[1;33m"
NC="\033[0m"

# Logging helpers
log() {
  printf '%b[INFO]%b %s\n' "$GREEN" "$NC" "$1"
}

warn() {
  printf '%b[WARN]%b %s\n' "$YELLOW" "$NC" "$1"
}

error() {
  printf '%b[ERROR]%b %s\n' "$RED" "$NC" "$1"
}

# Print a configuration section heading
print_config_heading() {
  printf '\n%b-- %s --%b\n' "$BLUE" "$1" "$NC"
}

# Show help
show_help() {
  printf '%bsing-box installation - VLESS + REALITY%b\n' "$BLUE" "$NC"
  printf 'Usage: %s [options]\n\n' "$0"
  printf 'Options:\n'
  printf '  %b%-12s%b %s\n' "$GREEN" '-port' "$NC" 'Listen port (1-65535, default: 443)'
  printf '  %b%-12s%b %s\n' "$GREEN" '-uuid' "$NC" 'UUID v4 (generated by default)'
  printf '  %b%-12s%b %s\n' "$GREEN" '-uninstall' "$NC" 'Uninstall and remove the binary and configuration'
  printf '  %b%-12s%b %s\n' "$GREEN" '-help' "$NC" 'Show help'
}

# Parse arguments
while [[ $# -gt 0 ]]; do
  case "$1" in
    -port)
      if [[ $# -lt 2 || ! "$2" =~ ^[0-9]+$ ]]; then
        error "Invalid port. Usage: -port 443 (1-65535)"
        exit 1
      fi
      PORT="$2"
      # Strip leading zeros and limit length to avoid octal interpretation and integer overflow.
      while [[ ${#PORT} -gt 1 && "$PORT" == 0* ]]; do
        PORT="${PORT:1}"
      done
      if [[ ${#PORT} -gt 5 ]] || (( 10#$PORT < 1 || 10#$PORT > 65535 )); then
        error "Invalid port. Usage: -port 443 (1-65535)"
        exit 1
      fi
      shift 2
      ;;
    -uuid)
      if [[ $# -lt 2 || ! "$2" =~ ^[[:xdigit:]]{8}-[[:xdigit:]]{4}-4[[:xdigit:]]{3}-[89aAbB][[:xdigit:]]{3}-[[:xdigit:]]{12}$ ]]; then
        error "Invalid UUID. -uuid only accepts UUID v4"
        exit 1
      fi
      UUID="$2"
      shift 2
      ;;
    -uninstall)
      UNINSTALL=true
      shift
      ;;
    -help)
      show_help
      exit 0
      ;;
    *)
      error "Unknown argument: $1"
      show_help
      exit 1
      ;;
  esac
done

# Require root privileges
if [ "$EUID" -ne 0 ]; then
  error "Root privileges required: sudo bash install.sh"
  exit 1
fi

# Uninstall
uninstall() {
  log "Uninstalling sing-box..."
  systemctl stop sing-box 2>/dev/null
  systemctl disable sing-box 2>/dev/null
  rm -f "$SERVICE_FILE"
  systemctl daemon-reload
  rm -rf "$BASE_DIR"
  log "Uninstall complete"
  exit 0
}

# Run the uninstaller when requested
if [ "$UNINSTALL" = true ]; then
  uninstall
fi

# Install dependencies
install_dependencies() {
  log "Installing dependencies..."
  if command -v apt-get > /dev/null; then
    apt-get update -qq && apt-get install -y -qq curl wget jq openssl || {
      error "Dependency installation failed. Check package repositories and network access"
      exit 1
    }
  elif command -v yum > /dev/null; then
    yum install -y -q curl wget jq openssl || {
      error "Dependency installation failed. Check package repositories and network access"
      exit 1
    }
  else
    error "Unsupported system. apt-get or yum is required"
    exit 1
  fi
  log "Dependencies are ready"
}

# Generate the default UUID and short ID after dependencies are ready
initialize_config_values() {
  if [[ -z "$UUID" ]]; then
    UUID=$(cat /proc/sys/kernel/random/uuid) || {
      error "Failed to generate UUID. Specify a UUID v4 with -uuid"
      exit 1
    }
    if [[ ! "$UUID" =~ ^[[:xdigit:]]{8}-[[:xdigit:]]{4}-4[[:xdigit:]]{3}-[89aAbB][[:xdigit:]]{3}-[[:xdigit:]]{12}$ ]]; then
      error "Generated UUID is invalid. Specify a UUID v4 with -uuid"
      exit 1
    fi
  fi
  SHORT_ID=$(openssl rand -hex 8) || {
    error "Failed to generate short ID. Check openssl"
    exit 1
  }
  if [[ -z "$SHORT_ID" ]]; then
    error "Short ID is empty. Check openssl"
    exit 1
  fi
}

# Detect system architecture
determine_architecture() {
  log "Detecting architecture..."
  ARCH=$(uname -m)
  case "$ARCH" in
    x86_64) ARCH="amd64" ;;
    aarch64) ARCH="arm64" ;;
    armv7l) ARCH="armv7" ;;
    armv6l) ARCH="armv6" ;;
    i386 | i686) ARCH="386" ;;
    mips64le) ARCH="mips64le" ;;
    mipsle) ARCH="mipsle" ;;
    ppc64le) ARCH="ppc64le" ;;
    riscv64) ARCH="riscv64" ;;
    s390x) ARCH="s390x" ;;
    loongarch64) ARCH="loong64" ;;
    *)
      error "Unsupported architecture: $ARCH"
      exit 1
      ;;
  esac
  log "Architecture: $ARCH"
}

# Install sing-box
install_sing_box() {
  log "Preparing installation..."
  mkdir -p "$INSTALL_DIR" || {
    error "Failed to create installation directory: $INSTALL_DIR"
    exit 1
  }

  # Fetch the latest version
  VERSION_RESPONSE=$(curl -fsS --connect-timeout 5 --max-time 10 https://api.github.com/repos/SagerNet/sing-box/releases/latest) &&
    LATEST_VERSION=$(printf '%s' "$VERSION_RESPONSE" | jq -r .tag_name) || LATEST_VERSION=""
  if [[ -z "$LATEST_VERSION" || "$LATEST_VERSION" == "null" ]]; then
    warn "Version lookup failed. Trying a fallback..."
    VERSION_RESPONSE=$(curl -fsS --connect-timeout 5 --max-time 10 https://api.github.com/repos/SagerNet/sing-box/tags) &&
      LATEST_VERSION=$(printf '%s' "$VERSION_RESPONSE" | jq -r '.[0].name') || LATEST_VERSION=""
    
    if [[ -z "$LATEST_VERSION" || "$LATEST_VERSION" == "null" ]]; then
      error "Version lookup failed. Check connectivity to GitHub"
      exit 1
    fi
  fi

  DOWNLOAD_URL="https://github.com/SagerNet/sing-box/releases/download/${LATEST_VERSION}/sing-box-${LATEST_VERSION:1}-linux-${ARCH}.tar.gz"
  log "Downloading sing-box ${LATEST_VERSION} (${ARCH})..."

  # Download and extract
  TEMP_DIR=$(mktemp -d /tmp/sing-box.XXXXXXXXXX) || {
    error "Failed to create temporary directory. Check /tmp"
    exit 1
  }
  wget -q --timeout=30 --tries=3 -O "$TEMP_DIR/sing-box.tar.gz" "$DOWNLOAD_URL" || {
    error "Download failed. Check connectivity to GitHub"
    exit 1
  }
  
  # Verify the downloaded file
  if [ -s "$TEMP_DIR/sing-box.tar.gz" ]; then
    log "Extracting package..."
  else
    error "Package is empty. Download it again"
    exit 1
  fi

  tar -xzf "$TEMP_DIR/sing-box.tar.gz" -C "$TEMP_DIR" || {
    error "Extraction failed. Check the package and available disk space"
    exit 1
  }

  # Move the binary and clean up
  mv "$TEMP_DIR/sing-box-${LATEST_VERSION:1}-linux-${ARCH}/sing-box" "$INSTALL_DIR/sing-box" || {
    error "Failed to install binary: $INSTALL_DIR"
    exit 1
  }

  cleanup_temp_files
  chmod +x "$INSTALL_DIR/sing-box" || {
    error "Failed to set executable permissions: $INSTALL_DIR/sing-box"
    exit 1
  }
  log "Binary: $INSTALL_DIR/sing-box"
}

# Generate a REALITY key pair
generate_reality_keypair() {
  log "Generating REALITY keys..."
  if ! REALITY_KEYPAIR=$("$INSTALL_DIR/sing-box" generate reality-keypair); then
    error "Failed to generate REALITY keys"
    exit 1
  fi
  PRIVATE_KEY=$(printf '%s\n' "$REALITY_KEYPAIR" | grep "PrivateKey" | awk '{print $2}' | tr -d '"')
  PUBLIC_KEY=$(printf '%s\n' "$REALITY_KEYPAIR" | grep "PublicKey" | awk '{print $2}' | tr -d '"')
  if [[ -z "$PRIVATE_KEY" || -z "$PUBLIC_KEY" ]]; then
    error "REALITY keys are incomplete"
    exit 1
  fi
  log "REALITY keys generated"
}

# Create the configuration file
create_config_file() {
  log "Saving configuration..."
  mkdir -p "$CONFIG_DIR" || {
    error "Failed to create configuration directory: $CONFIG_DIR"
    exit 1
  }
  if ! cat > "$CONFIG_FILE" <<EOF
{
  "inbounds": [
    {
      "type": "vless",
      "listen": "::",
      "listen_port": ${PORT},
      "users": [
        {
          "uuid": "${UUID}",
          "flow": "xtls-rprx-vision"
        }
      ],
      "tls": {
        "enabled": true,
        "server_name": "${DOMAIN}",
        "reality": {
          "enabled": true,
          "handshake": {
            "server": "${DOMAIN}",
            "server_port": 443
          },
          "private_key": "${PRIVATE_KEY}",
          "short_id": "${SHORT_ID}"
        }
      }
    }
  ],
  "outbounds": [
    {
      "type": "direct"
    }
  ]
}
EOF
  then
    error "Failed to save configuration: $CONFIG_FILE"
    exit 1
  fi
  log "Configuration: $CONFIG_FILE"
}

# Create the systemd service
create_systemd_service() {
  log "Setting up system service..."
  if ! cat > "$SERVICE_FILE" <<EOF
[Unit]
Description=sing-box
After=network.target

[Service]
Type=simple
ExecStart=${INSTALL_DIR}/sing-box run -c ${CONFIG_FILE}
Restart=on-failure
RestartSec=5s

[Install]
WantedBy=multi-user.target
EOF
  then
    error "Failed to save service file: $SERVICE_FILE"
    exit 1
  fi

  systemctl daemon-reload || {
    error "Failed to reload services: systemctl daemon-reload"
    exit 1
  }
  log "Service: $SERVICE_FILE"
}

# Print client configurations
print_client_config() {
  log "Fetching public IP address..."
  SERVER_IP=$(curl -fsS --connect-timeout 5 --max-time 10 https://api.ipify.org) || SERVER_IP=""
  if [[ -z "$SERVER_IP" ]]; then
    warn "Failed to fetch public IP address. Replace localhost with the server IP before importing"
    SERVER_IP="localhost"
  fi

  print_config_heading "VLESS"
  cat <<EOF
vless://${UUID}@${SERVER_IP}:${PORT}?encryption=none&flow=xtls-rprx-vision&security=reality&sni=${DOMAIN}&fp=chrome&publicKey=${PUBLIC_KEY}&shortId=${SHORT_ID}#${SERVER_IP}
EOF

  print_config_heading "Mihomo"
  cat <<EOF
proxies:
  - name: ${SERVER_IP}
    server: ${SERVER_IP}
    port: ${PORT}
    type: vless
    uuid: ${UUID}
    tls: true
    tfo: false
    udp: true
    flow: xtls-rprx-vision
    reality-opts:
      public-key: ${PUBLIC_KEY}
      short-id: ${SHORT_ID}
    servername: ${DOMAIN}
    client-fingerprint: chrome
    network: tcp
EOF

  print_config_heading "sing-box"
  cat <<EOF
{
  "outbounds": [
    {
      "type": "vless",
      "tag": "${SERVER_IP}",
      "server": "${SERVER_IP}",
      "server_port": ${PORT},
      "uuid": "${UUID}",
      "flow": "xtls-rprx-vision",
      "tls": {
        "enabled": true,
        "server_name": "${DOMAIN}",
        "utls": {
          "enabled": true,
          "fingerprint": "chrome"
        },
        "reality": {
          "enabled": true,
          "public_key": "${PUBLIC_KEY}",
          "short_id": "${SHORT_ID}"
        }
      }
    }
  ]
}
EOF
  printf '\n'
}

start_service() {
  local service_enabled=true
  log "Starting service..."
  systemctl start sing-box || {
    error "Failed to start service. Check logs: journalctl -u sing-box -n 50 --no-pager"
    exit 1
  }

  systemctl enable sing-box || {
    service_enabled=false
    warn "Failed to enable service at boot. Retry: systemctl enable sing-box"
  }

  # Check service status
  if systemctl is-active --quiet sing-box; then
    if [[ "$service_enabled" == true ]]; then
      log "Service started and enabled at boot"
    else
      log "Service started but could not be enabled at boot"
    fi
  else
    error "Service is not running. Check logs: journalctl -u sing-box -n 50 --no-pager"
    exit 1
  fi
}

# Only remove the temporary directory created by this installation
cleanup_temp_files() {
  if [[ -n "$TEMP_DIR" ]]; then
    if rm -rf -- "$TEMP_DIR"; then
      TEMP_DIR=""
    else
      warn "Failed to remove temporary directory: $TEMP_DIR"
    fi
  fi
}

# Handle interruption signals
cleanup() {
  printf '\n'
  warn "Installation interrupted. Cleaning up temporary files..."
  exit 1
}

# Register signal handlers
trap cleanup INT TERM
trap cleanup_temp_files EXIT

# Main function
main() {
  log "Installing sing-box - VLESS + REALITY"
  install_dependencies
  initialize_config_values
  determine_architecture
  install_sing_box
  generate_reality_keypair
  create_config_file
  create_systemd_service
  start_service
  log "Installation complete: $BASE_DIR"
  print_client_config
}

# Run the main function
main
